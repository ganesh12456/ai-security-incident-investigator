'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {execFileSync}=require('node:child_process');
const {investigate}=require('../functions/investigator/engine');
test('Slate build includes no bundled case records and processes a user import',()=>{
  const root=path.resolve(__dirname,'..');
  execFileSync(process.execPath,['scripts/build-slate.js'],{cwd:root});
  const output=path.join(root,'dist');
  const html=fs.readFileSync(path.join(output,'index.html'),'utf8');
  assert.match(html,/investigator\.browser\.js/);
  assert.doesNotMatch(html,/ALT-1001|DEMO EVENT WINDOW/);
  const source=fs.readFileSync(path.join(output,'investigator.browser.js'),'utf8');
  assert.doesNotMatch(source,/maya\.rao@northstar|fixtures\/scenarios|kev-snapshot/);
  const context={window:{},TextEncoder};
  vm.runInNewContext(source,context);
  const app=context.window.SignalDeskApp;
  const events=app.parseRecords('[{"timestamp":"2026-10-24T04:00:00Z","actor":"account-a","action":"login_failed","message":"Failed sign-in"}]').events;
  const result=app.investigate(events[0].id,{events});
  assert.equal(result.findings[0].id,investigate(events[0].id,{events}).findings[0].id);
  assert.match(app.reportText(result),/ROW-00001/);
});
